interface ThamSoDinhNghia {
  ma: MaYeuTo;
  loai: LoaiYeuTo;
  tenKhac?: readonly string[];
  trang: number;
  muc: string;
  tenGoc: string;
  ghiChu?: string;
  bang: BangChiNgayTheoChiThang;
}

function taoDinhNghia(thamSo: ThamSoDinhNghia): DinhNghiaYeuToTheoChiThang {
  return {
    ma: thamSo.ma,
    loai: thamSo.loai,
    tenKhac: thamSo.tenKhac ?? [],
    chiNgayTheoChiThang: thamSo.bang,
    nguon: taoNguonQuyen6(thamSo.trang, thamSo.muc, thamSo.tenGoc, thamSo.ghiChu),
  };
}

function taoNguonQuyen6(
  trang: number,
  muc: string,
  tenGoc: string,
  ghiChu?: string,
): readonly ThamChieuNguon[] {
  return [
    {
      loaiNguon: LoaiNguon.BAN_VIET,
      tap: 1,
      quyen: 6,
      trang,
      muc,
      tenGoc,
      ghiChu,
      daXacMinh: true,
    },
    {
      loaiNguon: LoaiNguon.HAN_BAN,
      quyen: 6,
      muc: tenGoc,
      tenGoc,
      ghiChu,
      daXacMinh: true,
    },
  ];
}
